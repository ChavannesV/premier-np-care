/** The editor and build use the same field definitions and limits. */
export type PageField =
  | { kind: "text"; label: string; max: number; multiline: boolean }
  | { kind: "array"; label: string; min: number; max: number; item: PageField }
  | { kind: "object"; label: string; fields: Record<string, PageField> };
export type PageDefinition = { label: string; route: string; fields: Record<string, PageField> };

const text = (label: string, max = 1200): PageField => ({ kind: "text", label, max, multiline: max > 320 });
const list = (label: string, item: PageField): PageField => ({ kind: "array", label, min: 1, max: 12, item });
const row = (label: string, fields: Record<string, PageField>): PageField => ({ kind: "object", label, fields });

